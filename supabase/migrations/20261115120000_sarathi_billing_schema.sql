-- ---------------------------------------------------------------------------
-- 10. Document numbering (atomic, gap-free counters per document kind)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.format_document_number(p_format text, p_prefix text, p_seq integer, p_padding integer, p_date date)
RETURNS text LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE
  v_year integer := extract(year FROM p_date)::integer;
  v_fy text;
BEGIN
  IF extract(month FROM p_date) >= 4 THEN
    v_fy := v_year::text || '-' || lpad(((v_year + 1) % 100)::text, 2, '0');
  ELSE
    v_fy := (v_year - 1)::text || '-' || lpad((v_year % 100)::text, 2, '0');
  END IF;
  RETURN replace(replace(replace(replace(COALESCE(NULLIF(p_format, ''), '{PREFIX}/{FY}/{SEQ}'),
    '{PREFIX}', p_prefix), '{FY}', v_fy), '{YYYY}', v_year::text), '{SEQ}', lpad(p_seq::text, p_padding, '0'));
END $$;

CREATE OR REPLACE FUNCTION public.allocate_number(p_kind text, p_date date DEFAULT CURRENT_DATE)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  s public.company_settings;
  v_seq integer;
  v_prefix text;
  v_number text;
  v_attempt integer := 0;
  v_exists boolean;
BEGIN
  IF NOT public.is_member() THEN
    RAISE EXCEPTION 'Not authorised';
  END IF;
  LOOP
    v_attempt := v_attempt + 1;
    IF p_kind = 'invoice' THEN
      UPDATE public.company_settings SET invoice_next_number = invoice_next_number + 1 WHERE id = 1 RETURNING * INTO s;
      v_seq := s.invoice_next_number - 1; v_prefix := s.invoice_prefix;
    ELSIF p_kind = 'quotation' THEN
      UPDATE public.company_settings SET quotation_next_number = quotation_next_number + 1 WHERE id = 1 RETURNING * INTO s;
      v_seq := s.quotation_next_number - 1; v_prefix := s.quotation_prefix;
    ELSIF p_kind = 'estimate' THEN
      UPDATE public.company_settings SET estimate_next_number = estimate_next_number + 1 WHERE id = 1 RETURNING * INTO s;
      v_seq := s.estimate_next_number - 1; v_prefix := s.estimate_prefix;
    ELSIF p_kind = 'receipt' THEN
      UPDATE public.company_settings SET receipt_next_number = receipt_next_number + 1 WHERE id = 1 RETURNING * INTO s;
      v_seq := s.receipt_next_number - 1; v_prefix := s.receipt_prefix;
    ELSE
      RAISE EXCEPTION 'Unknown document kind %', p_kind;
    END IF;

    v_number := public.format_document_number(s.number_format, v_prefix, v_seq, s.number_padding, COALESCE(p_date, CURRENT_DATE));

    IF p_kind = 'invoice' THEN
      SELECT EXISTS (SELECT 1 FROM public.invoices WHERE invoice_number = v_number) INTO v_exists;
    ELSIF p_kind IN ('quotation', 'estimate') THEN
      SELECT EXISTS (SELECT 1 FROM public.quotations WHERE quotation_number = v_number) INTO v_exists;
    ELSE
      SELECT EXISTS (SELECT 1 FROM public.payments WHERE receipt_number = v_number) INTO v_exists;
    END IF;

    EXIT WHEN NOT v_exists OR v_attempt > 500;
  END LOOP;
  RETURN v_number;
END $$;

-- ---------------------------------------------------------------------------
-- 11. Invoice balance & status maintenance
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.recalc_invoice(p_invoice_id uuid)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_paid numeric(14,2);
BEGIN
  IF auth.uid() IS NOT NULL AND NOT public.is_member() THEN
    RAISE EXCEPTION 'Not authorised';
  END IF;
  SELECT COALESCE(sum(amount), 0) INTO v_paid FROM public.payments WHERE invoice_id = p_invoice_id;
  PERFORM set_config('app.invoice_recalc', 'on', true);
  UPDATE public.invoices i SET
    amount_paid = v_paid,
    balance_due = round(i.net_payable - i.advance_paid - i.previous_payments - v_paid, 2),
    status = CASE
      WHEN i.status = 'Cancelled' THEN 'Cancelled'
      WHEN i.status = 'Draft' AND v_paid = 0 THEN 'Draft'
      WHEN round(i.net_payable - i.advance_paid - i.previous_payments - v_paid, 2) <= 0 THEN 'Paid'
      WHEN v_paid > 0 OR i.advance_paid > 0 OR i.previous_payments > 0 THEN 'Partially Paid'
      ELSE 'Sent'
    END,
    sent_at = CASE WHEN i.status = 'Draft' AND v_paid > 0 THEN COALESCE(i.sent_at, now()) ELSE i.sent_at END
  WHERE i.id = p_invoice_id;
  PERFORM set_config('app.invoice_recalc', 'off', true);
END $$;

-- Staff may not edit issued invoices except to cancel or log reminders.
CREATE OR REPLACE FUNCTION public.guard_invoice_update()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_allowed text[] := ARRAY['status', 'cancel_reason', 'cancelled_at', 'cancelled_by', 'sent_at', 'last_reminder_at', 'internal_notes', 'updated_at'];
BEGIN
  IF current_setting('app.invoice_recalc', true) = 'on' THEN
    RETURN NEW;
  END IF;
  IF OLD.status = 'Cancelled' AND NOT public.is_admin() THEN
    RAISE EXCEPTION 'Cancelled invoices cannot be modified.';
  END IF;
  IF OLD.status <> 'Draft' AND NOT public.is_admin() THEN
    IF (to_jsonb(NEW) - v_allowed) IS DISTINCT FROM (to_jsonb(OLD) - v_allowed) THEN
      RAISE EXCEPTION 'Only administrators can edit an issued invoice.';
    END IF;
    IF NEW.status NOT IN (OLD.status, 'Cancelled') THEN
      RAISE EXCEPTION 'Invoice status is maintained automatically from payments.';
    END IF;
  END IF;
  IF NEW.status = 'Cancelled' AND OLD.status <> 'Cancelled' THEN
    IF OLD.amount_paid > 0 THEN
      RAISE EXCEPTION 'Delete the recorded payments before cancelling this invoice.';
    END IF;
    NEW.cancelled_at := COALESCE(NEW.cancelled_at, now());
    NEW.cancelled_by := COALESCE(NEW.cancelled_by, auth.uid());
  END IF;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS invoices_guard ON public.invoices;
CREATE TRIGGER invoices_guard BEFORE UPDATE ON public.invoices
  FOR EACH ROW EXECUTE FUNCTION public.guard_invoice_update();

CREATE OR REPLACE FUNCTION public.before_payment_write()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  inv public.invoices;
  v_other numeric(14,2);
  v_limit numeric(14,2);
BEGIN
  SELECT * INTO inv FROM public.invoices WHERE id = NEW.invoice_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Invoice not found.';
  END IF;
  IF inv.status = 'Cancelled' THEN
    RAISE EXCEPTION 'Payments cannot be recorded against a cancelled invoice.';
  END IF;
  SELECT COALESCE(sum(amount), 0) INTO v_other FROM public.payments
    WHERE invoice_id = NEW.invoice_id AND (TG_OP = 'INSERT' OR id <> NEW.id);
  v_limit := inv.net_payable - inv.advance_paid - inv.previous_payments - v_other;
  IF NEW.amount > v_limit + 0.009 THEN
    RAISE EXCEPTION 'Payment of % exceeds the balance due of %.', NEW.amount, greatest(v_limit, 0);
  END IF;
  NEW.customer_id := inv.customer_id;
  IF NEW.receipt_number IS NULL OR NEW.receipt_number = '' THEN
    NEW.receipt_number := public.allocate_number('receipt', NEW.payment_date);
  END IF;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS payments_before_write ON public.payments;
CREATE TRIGGER payments_before_write BEFORE INSERT OR UPDATE ON public.payments
  FOR EACH ROW EXECUTE FUNCTION public.before_payment_write();

CREATE OR REPLACE FUNCTION public.after_payment_write()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF TG_OP IN ('UPDATE', 'DELETE') THEN
    PERFORM public.recalc_invoice(OLD.invoice_id);
  END IF;
  IF TG_OP IN ('INSERT', 'UPDATE') THEN
    PERFORM public.recalc_invoice(NEW.invoice_id);
  END IF;
  RETURN NULL;
END $$;

DROP TRIGGER IF EXISTS payments_after_write ON public.payments;
CREATE TRIGGER payments_after_write AFTER INSERT OR UPDATE OR DELETE ON public.payments
  FOR EACH ROW EXECUTE FUNCTION public.after_payment_write();

