  WITH CHECK (public.is_admin() OR (public.is_member() AND EXISTS (SELECT 1 FROM public.invoices i WHERE i.id = invoice_id AND i.status = 'Draft')));
DROP POLICY IF EXISTS invoice_items_update ON public.invoice_items;
CREATE POLICY invoice_items_update ON public.invoice_items FOR UPDATE TO authenticated
  USING (public.is_admin() OR (public.is_member() AND EXISTS (SELECT 1 FROM public.invoices i WHERE i.id = invoice_id AND i.status = 'Draft')))
  WITH CHECK (public.is_admin() OR (public.is_member() AND EXISTS (SELECT 1 FROM public.invoices i WHERE i.id = invoice_id AND i.status = 'Draft')));
