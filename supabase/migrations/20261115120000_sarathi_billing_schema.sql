CREATE TABLE IF NOT EXISTS public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email text NOT NULL DEFAULT '',
  full_name text NOT NULL DEFAULT '',
  role text NOT NULL DEFAULT 'staff' CHECK (role IN ('admin', 'staff')),
  active boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION public.is_member()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND active);
$$;

CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND active AND role = 'admin');
$$;

-- First user becomes admin; everyone else waits for approval.
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_first boolean;
BEGIN
  PERFORM pg_advisory_xact_lock(724001);
  SELECT NOT EXISTS (SELECT 1 FROM public.profiles) INTO v_first;
  INSERT INTO public.profiles (id, email, full_name, role, active)
  VALUES (
    NEW.id,
    COALESCE(NEW.email, ''),
    COALESCE(NEW.raw_user_meta_data ->> 'full_name', ''),
    CASE WHEN v_first THEN 'admin' ELSE 'staff' END,
    v_first
  )
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- Back-fill profiles for users that existed before this script ran.
INSERT INTO public.profiles (id, email, role, active)
SELECT u.id, COALESCE(u.email, ''),
       CASE WHEN row_number() OVER (ORDER BY u.created_at) = 1 AND NOT EXISTS (SELECT 1 FROM public.profiles) THEN 'admin' ELSE 'staff' END,
       (row_number() OVER (ORDER BY u.created_at) = 1 AND NOT EXISTS (SELECT 1 FROM public.profiles))
FROM auth.users u
WHERE NOT EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = u.id);

-- Only admins may change role/active; at least one active admin must remain.
CREATE OR REPLACE FUNCTION public.guard_profile_update()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF (NEW.role IS DISTINCT FROM OLD.role OR NEW.active IS DISTINCT FROM OLD.active) AND NOT public.is_admin() THEN
    RAISE EXCEPTION 'Only administrators can change roles or access.';
  END IF;
  NEW.id := OLD.id;
  NEW.email := OLD.email;
  IF (OLD.role = 'admin' AND OLD.active) AND (NEW.role <> 'admin' OR NOT NEW.active) THEN
    IF NOT EXISTS (SELECT 1 FROM public.profiles WHERE id <> OLD.id AND role = 'admin' AND active) THEN
      RAISE EXCEPTION 'At least one active administrator is required.';
    END IF;
  END IF;
  NEW.updated_at := now();
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS profiles_guard ON public.profiles;
CREATE TRIGGER profiles_guard BEFORE UPDATE ON public.profiles
  FOR EACH ROW EXECUTE FUNCTION public.guard_profile_update();

