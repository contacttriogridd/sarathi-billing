/*
  SARATHI ASSOCIATES — Construction Billing & Invoice Management
  Complete database schema for Supabase (PostgreSQL).

  HOW TO APPLY
  ------------
  Option A (dashboard): Supabase Dashboard → SQL Editor → paste this whole file → Run.
  Option B (CLI):       supabase link --project-ref <ref> && supabase db push

  The script is idempotent: it can be re-run safely and never deletes data.

  SECURITY MODEL
  --------------
  * One shared company workspace. Every signed-in user has a row in `profiles`.
  * The FIRST user who signs up becomes an active ADMIN automatically.
  * Everyone who signs up afterwards is created as an INACTIVE STAFF member and
    cannot read any billing data until an admin activates them (Settings → Team).
  * Admin: full access, company settings, team management, deletes, restore.
  * Staff: create/edit customers, projects, drafts, quotations, payments and
    expenses. Staff cannot delete records, edit issued invoices, or change settings.
  * Row Level Security is enabled on every table. The anon role has no access.
*/

